function countUp(el){
  const target=+el.dataset.n, suf=el.dataset.suf||'';
  const t0=performance.now(), dur=1400;
  function tick(now){
    const k=Math.min(1,(now-t0)/dur), e=1-Math.pow(1-k,3);
    el.textContent=Math.round(target*e).toLocaleString()+suf;
    if(k<1)requestAnimationFrame(tick);
  }
  requestAnimationFrame(tick);
}
const IO=('IntersectionObserver' in window)?new IntersectionObserver(es=>es.forEach(e=>{
  if(e.isIntersecting){
    e.target.classList.add('in');
    e.target.querySelectorAll('[data-n]').forEach(n=>{if(!n.dataset.done){n.dataset.done=1;countUp(n)}});
    IO.unobserve(e.target);
  }
}),{threshold:.08,rootMargin:'0px 0px -30px 0px'}):null;
function obsRev(){
  if(!IO){document.querySelectorAll('.rev').forEach(el=>el.classList.add('in'));return}
  document.querySelectorAll('.rev:not(.in)').forEach(el=>IO.observe(el));
}
